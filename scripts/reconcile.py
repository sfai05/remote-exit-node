#!/usr/bin/env python3
"""Make host_vars/<NODE>/ match the answers collected by scripts/setup.sh.

Runs with Ansible's Python (needs `ansible` and `yaml`); inputs come from the environment.
Existing WireGuard keys and addresses are kept, peers new to WG_PEERS get keys, peers removed
from it are revoked after confirmation. Writes setup.yml (generated) and vault.yml (encrypted
in memory); never touches the user's vars.yml except for a one-time migration.
"""
import os
import re
import subprocess
import sys

import yaml
from ansible.constants import DEFAULT_VAULT_ID_MATCH
from ansible.errors import AnsibleError
from ansible.parsing.vault import VaultLib, VaultSecret

GENERATED_KEYS = {
    "ansible_become_pass", "node_timezone", "node_hostname", "enable_duckdns", "duckdns_domain",
    "enable_wireguard", "wireguard_port", "wireguard_endpoint", "wireguard_ipv4_network",
    "wireguard_ipv4_server", "wireguard_ipv6_network", "wireguard_ipv6_server", "wireguard_peers",
}
PEER_KEYS = {"name", "ipv4", "ipv6", "private_key", "public_key"}
SECRETS = {
    "vault_become_pass": "BECOME_PASS",
    "vault_tailscale_authkey": "TAILSCALE_AUTHKEY",
    "vault_duckdns_token": "DUCKDNS_TOKEN",
    "vault_monitoring_heartbeat_url": "HEARTBEAT_URL",
}
HEADER = "# Generated by scripts/setup.sh"


class Loader(yaml.SafeLoader):
    pass


# Secrets are stored tagged !unsafe (so Ansible never templates them); here they're plain strings.
Loader.add_constructor("!unsafe", lambda loader, node: loader.construct_scalar(node))


def die(msg):
    sys.exit(f"error: {msg}")


def load_yaml(text):
    return yaml.load(text, Loader=Loader) or {}


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write_if_changed(path, text):
    if os.path.exists(path) and read(path) == text:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def quote(value, unsafe=False):
    if value in (None, ""):
        return "''"
    quoted = "'" + str(value).replace("'", "''") + "'"
    return f"!unsafe {quoted}" if unsafe else quoted


def keypair():
    def wg(*args, stdin=None):
        return subprocess.run(["wg", *args], input=stdin, capture_output=True, text=True,
                              check=True).stdout.strip()
    private = wg("genkey")
    return {"private_key": private, "public_key": wg("pubkey", stdin=private)}


def confirm(question):
    try:
        with open("/dev/tty", encoding="utf-8") as tty:
            print(f"{question} [y/N]: ", end="", flush=True)
            return tty.readline().strip().lower().startswith("y")
    except OSError:
        return False


def main():
    env = os.environ
    node = env["NODE"]
    host_dir = os.path.join("host_vars", node)
    setup_file = os.path.join(host_dir, "setup.yml")
    vars_file = os.path.join(host_dir, "vars.yml")
    vault_file = os.path.join(host_dir, "vault.yml")
    os.makedirs(host_dir, exist_ok=True)

    vault = VaultLib([(DEFAULT_VAULT_ID_MATCH, VaultSecret(env["VAULT_PASS"].encode()))])
    old_vault_text = ""
    if os.path.exists(vault_file):
        try:
            old_vault_text = vault.decrypt(read(vault_file).encode()).decode()
        except AnsibleError:
            die(f"cannot decrypt {vault_file}: wrong vault password?")
    secrets = load_yaml(old_vault_text)

    # Previous generated vars: setup.yml, or a pre-split vars.yml written by older setup.sh.
    legacy_vars = os.path.exists(vars_file) and HEADER in read(vars_file)
    previous = {}
    for path in (setup_file, vars_file if legacy_vars else None):
        if path and os.path.exists(path):
            previous = load_yaml(read(path))
            break

    # Secrets: a non-empty value from the env file wins, otherwise keep what the vault has.
    for key, var in SECRETS.items():
        if env.get(var):
            secrets[key] = env[var]
        secrets.setdefault(key, "")
    if env.get("DUCKDNS_DOMAIN") and not secrets["vault_duckdns_token"]:
        die("DuckDNS is enabled but there is no token: set DUCKDNS_TOKEN in the env file")

    peers = env.get("WG_PEERS", "").split()
    added, removed, moved = [], [], []
    hosts = {}
    v6 = ""
    if peers:
        subnet = env["WG_SUBNET"]
        b, c = re.fullmatch(r"10\.(\d+)\.(\d+)", subnet).groups()
        v6 = "fd88:88:" if subnet == "10.88.0" else f"fd10:{b}:{c}:"

        existing = secrets.get("vault_wireguard_peers") or {}
        removed = [n for n in existing if n not in peers]
        if removed and not confirm(
                f"Remove {', '.join(removed)} from {node}? Their client configs stop working"):
            die("nothing changed; add them back to WG_PEERS or confirm the removal")
        added = [n for n in peers if n not in existing]
        secrets["vault_wireguard_server"] = secrets.get("vault_wireguard_server") or keypair()
        secrets["vault_wireguard_peers"] = {n: existing.get(n) or keypair() for n in peers}

        # Keep each peer's address; new peers get the next free host numbers in the subnet.
        old = {p["name"]: p for p in previous.get("wireguard_peers", []) if "name" in p}
        for n in peers:
            ip = str(old.get(n, {}).get("ipv4", ""))
            if ip.startswith(subnet + "."):
                hosts[n] = int(ip.rsplit(".", 1)[1])
            elif n in old:
                moved.append(n)
        nxt = max(hosts.values(), default=1) + 1
        for n in peers:
            if n not in hosts:
                hosts[n] = nxt
                nxt += 1
        if nxt > 255:
            die(f"more peers than addresses in {subnet}.0/24")

    # vault.yml
    lines = ["---"] + [f"{k}: {quote(secrets.get(k), unsafe=True)}" for k in SECRETS]
    if "vault_wireguard_server" in secrets:
        s = secrets["vault_wireguard_server"]
        lines += ["vault_wireguard_server:",
                  f"  private_key: {quote(s['private_key'])}",
                  f"  public_key: {quote(s['public_key'])}"]
    if "vault_wireguard_peers" in secrets:
        lines.append("vault_wireguard_peers:")
        for n, k in secrets["vault_wireguard_peers"].items():
            lines += [f"  {n}:", f"    private_key: {quote(k['private_key'])}",
                      f"    public_key: {quote(k['public_key'])}"]
    handled = set(SECRETS) | {"vault_wireguard_server", "vault_wireguard_peers"}
    extra = {k: v for k, v in secrets.items() if k not in handled}
    if extra:
        lines.append(yaml.safe_dump(extra, default_flow_style=False, sort_keys=False).rstrip())
    vault_text = "\n".join(lines) + "\n"
    vault_changed = vault_text != old_vault_text
    if vault_changed:
        with open(vault_file, "wb") as f:
            f.write(vault.encrypt(vault_text))

    # setup.yml
    out = ["---", f"{HEADER} from the env file. Don't edit: change the env file and re-run",
           "# setup.sh. Your own settings go in vars.yml, which overrides this file.",
           'ansible_become_pass: "{{ vault_become_pass }}"',
           f"node_timezone: {quote(env['NODE_TIMEZONE'])}"]
    if env.get("NODE_HOSTNAME"):
        out.append(f"node_hostname: {quote(env['NODE_HOSTNAME'])}")
    if env.get("DUCKDNS_DOMAIN"):
        out += ["enable_duckdns: true", f"duckdns_domain: {env['DUCKDNS_DOMAIN']}"]
    else:
        out.append("enable_duckdns: false")
    if peers:
        out += ["enable_wireguard: true", f"wireguard_port: {env['WG_PORT']}"]
        if env.get("WG_ENDPOINT"):
            out.append(f"wireguard_endpoint: {quote(env['WG_ENDPOINT'])}")
        if subnet != "10.88.0":
            out += [f"wireguard_ipv4_network: {subnet}.0/24", f"wireguard_ipv4_server: {subnet}.1",
                    f"wireguard_ipv6_network: '{v6}:/64'", f"wireguard_ipv6_server: '{v6}:1'"]
        out.append("wireguard_peers:")
        for n in peers:
            out += [f"  - name: {n}", f"    ipv4: {subnet}.{hosts[n]}", f'    ipv6: "{v6}:{hosts[n]}"',
                    f"    private_key: \"{{{{ vault_wireguard_peers['{n}'].private_key }}}}\"",
                    f"    public_key: \"{{{{ vault_wireguard_peers['{n}'].public_key }}}}\""]
    else:
        out.append("enable_wireguard: false")
    setup_changed = write_if_changed(setup_file, "\n".join(out) + "\n")

    # One-time migration: the old all-in-one vars.yml becomes setup.yml + your own vars.yml.
    if legacy_vars:
        old_vars = load_yaml(read(vars_file))
        mine = {k: v for k, v in old_vars.items() if k not in GENERATED_KEYS}
        options = {p["name"]: {k: v for k, v in p.items() if k not in PEER_KEYS}
                   for p in old_vars.get("wireguard_peers", []) if "name" in p}
        options = {n: o for n, o in options.items() if o}
        if options:
            mine["wireguard_peer_options"] = options
        os.replace(vars_file, vars_file + ".old")
        if mine:
            write_if_changed(vars_file, "---\n# Your settings; scripts/setup.sh never changes this file.\n"
                             + yaml.safe_dump(mine, default_flow_style=False, sort_keys=False))
        print(f"Migrated: generated settings now in {setup_file}; your own settings "
              f"{'kept in ' + vars_file if mine else '(none found)'}; old file at {vars_file}.old")

    for n in moved:
        print(f"  {n}: moved to {subnet}.{hosts[n]} (subnet changed): re-import its client config")
    if peers:
        kept = [n for n in peers if n not in added]
        print(f"WireGuard: {len(kept)} kept" + (f", added {' '.join(added)}" if added else "")
              + (f", removed {' '.join(removed)}" if removed else ""))
    print(f"{vault_file}: {'updated' if vault_changed else 'unchanged'}; "
          f"{setup_file}: {'updated' if setup_changed else 'unchanged'}")


if __name__ == "__main__":
    main()
